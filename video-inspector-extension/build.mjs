import { build } from 'esbuild';
import { cp, mkdir, readdir, rm } from 'node:fs/promises';
import { resolve } from 'node:path';

// 标准结构：
//   src/content/**  content script 源码（ES modules）
//   src/            其余扩展文件（manifest / background / offscreen / lib / icons ...）
//   dist/           打包产物（content.js 由 esbuild 生成，其余原样复制）
const root = process.cwd();
const src = resolve(root, 'src');
const dist = resolve(root, 'dist');

await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });

// 1. content script 是 classic script，源码拆成 ES modules，这里统一打包成单个 IIFE
await build({
  entryPoints: [resolve(src, 'content/index.js')],
  outfile: resolve(dist, 'content.js'),
  bundle: true,
  format: 'iife',
  target: ['chrome100'],
  charset: 'utf8',
  legalComments: 'none',
  logLevel: 'info',
  banner: {
    js: '/* video-inspector content bundle - generated by build.mjs, edit src/content instead */'
  }
});

// 2. 其余静态文件原样复制，跳过 content 源码目录
for (const name of await readdir(src)) {
  if (name === 'content') continue;
  await cp(resolve(src, name), resolve(dist, name), { recursive: true, force: true });
}

console.log('[build] dist/ ready');
